"""Stage 0 – locate the input files, copy them to sources/original-pdfs and
record them (hash, size, pages) in sources/manifest.yaml.

The PDFs themselves are git-ignored: usage rights for redistribution are not
clarified (see docs/sources-and-rights.md). The manifest is what the repository
carries instead – enough to verify that a local copy is the exact same file.
Hand-written manifest fields (rights, notes) survive every re-run.
"""
from __future__ import annotations

import shutil
from pathlib import Path

import pymupdf
import yaml

from . import config
from .cache import sha256_file, write_if_changed

GENERATED_KEYS = {"file", "original_name", "sha256", "bytes", "pages", "kind", "trust"}


def _find_input(pattern: str) -> Path | None:
    hits = sorted(config.INPUT_DIR.glob(pattern))
    return hits[0] if hits else None


def load_manifest() -> dict:
    if not config.MANIFEST.exists():
        return {"sources": {}}
    return yaml.safe_load(config.MANIFEST.read_text(encoding="utf-8")) or {"sources": {}}


def source_path(source_id: str) -> Path:
    """Local path of an ingested source; raises with a helpful message if absent."""
    entry = load_manifest()["sources"].get(source_id)
    if not entry:
        raise SystemExit(f"Source '{source_id}' not in manifest – run `python -m pipeline ingest`.")
    path = config.ROOT / entry["file"]
    if not path.exists():
        raise SystemExit(f"{path} missing. Put the original into input/ and run ingest.")
    return path


def run(dry_run: bool = False, **_) -> None:
    manifest = load_manifest()
    sources = manifest.setdefault("sources", {})
    for sid, (pattern, canonical, kind, trust) in config.SOURCES.items():
        src = _find_input(pattern)
        dest = config.ORIGINALS_DIR / canonical
        if src is None and not dest.exists():
            print(f"[ingest] MISSING {sid}: no file matching '{pattern}' in {config.INPUT_DIR}")
            continue
        if src is not None:
            src_hash = sha256_file(src)
            if dest.exists() and sha256_file(dest) == src_hash:
                print(f"[ingest] {sid}: unchanged")
            elif dry_run:
                print(f"[ingest] would copy {src.name} -> {dest.relative_to(config.ROOT)}")
            else:
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, dest)
                print(f"[ingest] {sid}: copied")
        if dry_run or not dest.exists():
            continue
        entry = {k: v for k, v in sources.get(sid, {}).items() if k not in GENERATED_KEYS}
        pages = pymupdf.open(dest).page_count if dest.suffix == ".pdf" else None
        sources[sid] = {
            "file": dest.relative_to(config.ROOT).as_posix(),
            "original_name": src.name if src else sources.get(sid, {}).get("original_name"),
            "sha256": sha256_file(dest),
            "bytes": dest.stat().st_size,
            "pages": pages,
            "kind": kind,
            "trust": trust,
            **entry,
        }
    if dry_run:
        return
    header = ("# Generated by `python -m pipeline ingest`. Hand-written keys other than\n"
              f"# {sorted(GENERATED_KEYS)} are preserved across runs.\n")
    body = yaml.safe_dump(manifest, allow_unicode=True, sort_keys=False, width=100)
    if write_if_changed(config.MANIFEST, header + body):
        print(f"[ingest] wrote {config.MANIFEST.relative_to(config.ROOT)}")
