"""Stage "extract-figures": crop every curated figure and write figures/manifest.json.

Layer (A) of each figure is a PNG crop of the scan at its native resolution
(200 dpi), palette-quantised to 64 colours: visually lossless for these line
drawings and ~3× smaller than a true-colour PNG. The manifest then joins, per
figure, everything the repository knows about it:

  (A) figures/originals/<id>.png        – this stage
  (B) curation/figures/<id>.yaml        – curated metadata (axes, elements, …)
  (C) figures/reconstructed/<id>.svg    – hand-made faithful vector reconstruction
  (D) figures/exercises/<id>-blank.svg  – generated by `exercises`
      learning/drawing-exercises/<id>-zeichenuebung.md

Crops are only rendered when their key (PDF hash, page, bbox, dpi, version)
changes – a second run renders nothing.
"""
from __future__ import annotations

import io
import json

import pymupdf
from PIL import Image

from . import catalog, config, outline
from .cache import dump_json, key_for, sha256_file, write_bytes_if_changed
from .ingest import source_path

PAD = 3.0          # pt of white margin around the graphic
COLOURS = 64
STAMP = config.STAMPS / "extract-figures.json"


def _png(page: pymupdf.Page, bbox: list[float]) -> bytes:
    r = pymupdf.Rect(bbox[0] - PAD, bbox[1] - PAD, bbox[2] + PAD, bbox[3] + PAD) & page.rect
    pix = page.get_pixmap(dpi=config.CROP_DPI, clip=r)
    img = Image.open(io.BytesIO(pix.tobytes("png"))).convert("RGB")
    out = io.BytesIO()
    img.quantize(COLOURS, method=Image.Quantize.MEDIANCUT).save(out, "PNG", optimize=True)
    return out.getvalue()


def _rel(path) -> str | None:
    return path.relative_to(config.ROOT).as_posix() if path.exists() else None


def manifest_entry(f: dict) -> dict:
    fid = f["id"]
    meta = catalog.figure_meta(fid)
    section = outline.section_at(f["pdf_page"], f["bbox"][1])
    sub = outline.subsection_at(f["pdf_page"], f["bbox"][1])
    png = config.FIG_ORIGINALS / f"{fid}.png"
    svg = config.FIG_RECONSTRUCTED / f"{fid}.svg"
    blank = config.FIG_EXERCISES / f"{fid}-blank.svg"
    guide = config.DRAWING_GUIDES / config.drawing_guide_name(fid)
    files = {"original": _rel(png), "reconstructed": _rel(svg), "exercise": _rel(blank),
             "drawing_guide": _rel(guide), "metadata": _rel(config.FIGURE_META_DIR / f"{fid}.yaml")}
    status = meta.get("reconstruction", {}).get("status", "not-started")
    entry = {
        "id": fid,
        "kind": f["kind"],
        "label": catalog.figure_label(f),
        "number": f.get("number"),
        "title": f["title"],
        "pdf_page": f["pdf_page"],
        "printed_page": catalog.printed_page(f["pdf_page"]),
        "bbox": f["bbox"],
        "chapter": section.chapter_id if section else None,
        "section": section.number if section else None,
        "subsection": sub.number if sub else None,
        "files": files,
        "reconstruction_status": status,
        "exam_relevance": meta.get("exam_relevance", {}).get("level"),
        "drawing_difficulty": meta.get("drawing", {}).get("difficulty"),
        "metadata_status": "curated" if meta else "missing",
    }
    for key in ("latex", "note", "bbox_note"):
        if f.get(key):
            entry[key] = f[key]
    if png.exists():
        with Image.open(png) as im:
            entry["pixels"] = list(im.size)
        entry["sha256"] = sha256_file(png)
    return entry


def run(pages: str | None = None, dry_run: bool = False, force: bool = False) -> int:
    pdf_path = source_path(config.SKRIPT)
    pdf_hash = sha256_file(pdf_path)
    doc = pymupdf.open(pdf_path)
    stamps = json.loads(STAMP.read_text(encoding="utf-8")) if STAMP.exists() else {}
    version = config.STAGE_VERSIONS["extract-figures"]
    wanted = None
    if pages:
        from .pages import parse_pages
        wanted = set(parse_pages(pages, doc.page_count))
    rendered = skipped = 0
    for f in catalog.figures():
        if wanted is not None and f["pdf_page"] not in wanted:
            continue
        out = config.FIG_ORIGINALS / f"{f['id']}.png"
        key = key_for(pdf_hash, f["pdf_page"], f["bbox"], config.CROP_DPI, PAD, COLOURS, version)
        if not force and stamps.get(f["id"]) == key and out.exists():
            skipped += 1
            continue
        if dry_run:
            print(f"[extract-figures] würde {f['id']} (S. {f['pdf_page']}) ausschneiden")
            continue
        write_bytes_if_changed(out, _png(doc[f["pdf_page"] - 1], f["bbox"]))
        stamps[f["id"]] = key
        rendered += 1
    if dry_run:
        return 0
    dump_json(STAMP, stamps)
    manifest = {
        "_comment": "Generiert von `python -m pipeline extract-figures` – nicht von Hand bearbeiten. "
                    "Quelle der Wahrheit: curation/figures.yaml und curation/figures/<id>.yaml.",
        "source": config.SKRIPT,
        "crop_dpi": config.CROP_DPI,
        "figures": [manifest_entry(f) for f in catalog.figures()],
        "duplicates_not_extracted": catalog.duplicates(),
    }
    changed = dump_json(config.FIG_MANIFEST, manifest)
    print(f"[extract-figures] gerendert={rendered} unverändert={skipped} "
          f"| manifest {'geschrieben' if changed else 'unverändert'}")
    return 0
